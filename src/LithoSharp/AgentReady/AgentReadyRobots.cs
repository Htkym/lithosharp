using System.Text;

namespace LithoSharp.AgentReady;

public enum AgentReadyRobotsMode
{
    Disabled,
    Generated,
    External,
}

/// <summary>Explicit robots rules. No crawler or training policy is added implicitly.</summary>
public sealed record AgentReadyRobotsGroup
{
    public IReadOnlyList<string> UserAgents { get; init; } = ["*"];
    public IReadOnlyList<string> Allow { get; init; } = [];
    public IReadOnlyList<string> Disallow { get; init; } = [];
}

public sealed record AgentReadyRobotsOptions
{
    public AgentReadyRobotsMode Mode { get; init; }
    public IReadOnlyList<AgentReadyRobotsGroup> Groups { get; init; } = [];
}

internal static class AgentReadyRobots
{
    internal static string? Build(string baseUrl, string? sitemapUrl, AgentReadyRobotsOptions options)
    {
        ArgumentNullException.ThrowIfNull(options);
        if (!Enum.IsDefined(options.Mode))
            throw new ArgumentOutOfRangeException(nameof(options), "Unknown robots management mode.");
        if (options.Mode != AgentReadyRobotsMode.Generated)
            return null;
        var root = new Uri(AgentReadyMetadata.RequireHttpUrl(baseUrl), UriKind.Absolute);
        if (root.AbsolutePath != "/" || root.Query.Length != 0)
            throw new InvalidOperationException("Generated robots.txt requires an origin-root site. Select External management for a subpath site.");
        var builder = new StringBuilder("# Generated by LithoSharp. Robots directives are not access control.\n");
        foreach (var group in options.Groups)
        {
            ArgumentNullException.ThrowIfNull(group);
            if (group.UserAgents.Count == 0)
                throw new ArgumentException("A robots group requires at least one user-agent.", nameof(options));
            builder.Append('\n');
            foreach (var agent in group.UserAgents)
            {
                if (string.IsNullOrWhiteSpace(agent) || agent.Any(character => !(char.IsAsciiLetterOrDigit(character) || character is '*' or '_' or '-')))
                    throw new ArgumentException("A robots user-agent must be a product token or '*'.", nameof(options));
                builder.Append("User-agent: ").Append(agent).Append('\n');
            }
            foreach (var path in group.Disallow)
                Rule("Disallow", path);
            foreach (var path in group.Allow)
                Rule("Allow", path);
        }
        if (sitemapUrl is not null)
        {
            var sitemap = new Uri(AgentReadyMetadata.RequireHttpUrl(sitemapUrl), UriKind.Absolute);
            if (sitemap.Query.Length != 0 || !string.Equals(root.GetLeftPart(UriPartial.Authority), sitemap.GetLeftPart(UriPartial.Authority), StringComparison.OrdinalIgnoreCase))
                throw new ArgumentException("The generated sitemap must belong to this site's origin.", nameof(sitemapUrl));
            builder.Append("\nSitemap: ").Append(sitemapUrl).Append('\n');
        }
        return builder.ToString();

        void Rule(string name, string path)
        {
            if (path is null || path.Any(character => char.IsControl(character) || character is '#' || char.IsWhiteSpace(character))
                || path.Length != 0 && !path.StartsWith("/", StringComparison.Ordinal))
                throw new ArgumentException("A robots path must be empty or start with '/', without whitespace or comments.", nameof(options));
            builder.Append(name).Append(": ").Append(path).Append('\n');
        }
    }
}
