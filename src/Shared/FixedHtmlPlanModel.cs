using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using LithoSharp.Routing;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;

namespace LithoSharp.Internal;

// Shared compiler model and exact emitted owner shape. No user code or runtime assembly is executed.
internal sealed class FixedHtmlPlanModel
{
    internal const string Contract = "fixed-full-html-plan/2;decoded-anchors/1";
    internal INamedTypeSymbol Symbol { get; }
    internal string BaseUrl { get; }
    internal IReadOnlyList<FixedHtmlPageModel> Pages { get; }
    private FixedHtmlPlanModel(INamedTypeSymbol symbol, string baseUrl, List<FixedHtmlPageModel> pages)
    {
        Symbol = symbol;
        BaseUrl = baseUrl;
        Pages = pages;
    }

    internal static bool Core(ITypeSymbol? symbol, string name) => symbol?.ToDisplayString() == name
        && symbol.ContainingAssembly.Identity.Name == "LithoSharp" && !symbol.Locations.Any(location => location.IsInSource);

    internal static FixedHtmlPlanModel? Read(INamedTypeSymbol symbol, CancellationToken token)
    {
        if (!symbol.IsStatic || symbol.Arity != 0 || symbol.IsFileLocal || symbol.ContainingType is not null
            || !symbol.DeclaringSyntaxReferences.Any(r => r.GetSyntax(token) is ClassDeclarationSyntax c && c.Modifiers.Any(SyntaxKind.PartialKeyword)))
            return null;
        var declarations = symbol.GetAttributes().Where(a => Core(a.AttributeClass, "LithoSharp.Content.FixedHtmlSiteAttribute")).ToArray();
        if (declarations.Length != 1)
            return null;
        var attribute = declarations[0];
        if (attribute.ConstructorArguments.Length != 1 || attribute.ConstructorArguments[0].Value is not string baseUrl
            || !Uri.TryCreate(baseUrl, UriKind.Absolute, out var address) || address.Scheme is not ("http" or "https")
            || address.UserInfo.Length != 0 || address.Query.Length != 0 || address.Fragment.Length != 0)
            return null;
        var pages = new List<FixedHtmlPageModel>();
        foreach (var method in symbol.GetMembers().OfType<IMethodSymbol>().OrderBy(m => m.Name, StringComparer.Ordinal))
        {
            token.ThrowIfCancellationRequested();
            var attributes = method.GetAttributes().Where(a => Core(a.AttributeClass, "LithoSharp.Content.FixedHtmlPageAttribute")).ToArray();
            if (attributes.Length == 0)
                continue;
            if (attributes.Length != 1)
                return null;
            var page = attributes[0];
            if (!method.IsStatic || method.Arity != 0 || method.Parameters.Length != 0 || method.IsAsync
                || method.MethodKind != MethodKind.Ordinary || !Core(method.ReturnType, "LithoSharp.IHtmlContent")
                || page.ConstructorArguments.Length != 1 || page.ConstructorArguments[0].Value is not string path
                || method.DeclaringSyntaxReferences.Length != 1)
                return null;
            try
            {
                var route = SiteRoute.ForFile(path, baseUrl);
                if (!(route.RelativeOutputPath.EndsWith(".html", StringComparison.OrdinalIgnoreCase)
                    || route.RelativeOutputPath.EndsWith(".htm", StringComparison.OrdinalIgnoreCase))
                    || pages.Any(p => string.Equals(p.OutputPath, route.RelativeOutputPath, StringComparison.OrdinalIgnoreCase)))
                    return null;
                pages.Add(new FixedHtmlPageModel(method, route.PublicPath, route.RelativeOutputPath));
            }
            catch (Exception e) when (e is ArgumentException or UriFormatException)
            {
                return null;
            }
        }
        return pages.Count == 0 ? null : new FixedHtmlPlanModel(symbol, baseUrl, pages);
    }

    internal static string? Fingerprint(Compilation compilation, IEnumerable<AdditionalText> files, AnalyzerConfigOptionsProvider options, CancellationToken token)
    {
        var inputs = StaticManifestFingerprint.Create(compilation, files, options, token);
        // The existing framed fingerprint covers full source, options, AdditionalTexts and reference MVIDs.
        // This separate contract includes the anchor projection and the immutable artifact owner version.
        return inputs is null ? null : Contract + ":" + inputs;
    }

    // Top-level nongeneric identities contain '.' namespace separators, never '_' substitutions.
    internal string Hint => Symbol.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat) + ".FixedHtml.g.cs";
    internal string Emit(string fingerprint)
    {
        static string Literal(string value) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);
        var text = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!Symbol.ContainingNamespace.IsGlobalNamespace)
            text.Append("namespace ").Append(Symbol.ContainingNamespace.ToDisplayString()).Append(" {\n");
        text.Append(Symbol.DeclaredAccessibility == Accessibility.Public ? "public" : "internal").Append(" static partial class @").Append(Symbol.Name).Append(" {\n")
            .Append("// ").Append(fingerprint).Append("\n")
            .Append("public static global::LithoSharp.Content.FixedHtmlSitePlan FixedHtmlPlan => new global::LithoSharp.Content.FixedHtmlSitePlan(")
            .Append(Literal(BaseUrl)).Append(", new string[] {\n");
        foreach (var page in Pages)
            text.Append(Literal(page.OutputPath)).Append(",\n");
        text.Append("}, new string[] {\n");
        foreach (var page in Pages)
            text.Append('@').Append(page.Method.Name).Append("().ToHtmlString(),\n");
        text.Append("});\n}\n");
        if (!Symbol.ContainingNamespace.IsGlobalNamespace)
            text.Append("}\n");
        return text.ToString();
    }
}

internal sealed class FixedHtmlPageModel(IMethodSymbol method, string publicPath, string outputPath)
{
    internal IMethodSymbol Method { get; } = method;
    internal string PublicPath { get; } = publicPath;
    internal string OutputPath { get; } = outputPath;
}
