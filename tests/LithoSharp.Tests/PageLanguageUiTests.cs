using LithoSharp.Configuration;
using LithoSharp.Mdx;
using LithoSharp.Pages;
using LithoSharp.Routing;

namespace LithoSharp.Tests;

public sealed class PageLanguageUiTests
{
    [Test]
    [Arguments(false)]
    [Arguments(true)]
    public async Task DocumentationVariantLocalizesTableOfContentsAndPreservesCustomText(bool customizeText)
    {
        using var workspace = new TemporaryWorkspace();
        var input = Path.Combine(workspace.Root, "input");
        Directory.CreateDirectory(input);
        await File.WriteAllTextAsync(Path.Combine(input, "with-heading.md"), "---\ntitle: With heading\n---\n## Section\n");
        await File.WriteAllTextAsync(Path.Combine(input, "without-heading.md"), "---\ntitle: Without heading\n---\nBody.\n");
        await using var docs = new DocumentationSite(new(workspace.Root) { NodeExecutable = "must-not-start-node" });
        docs.AddCollection(new("guide",
        [
            new("current", "en", input, "guide/en"),
            new("current", "ja", input, "guide/ja")
        ])
        { UseMdx = false });
        var text = customizeText ? SiteText.English with
        {
            TableOfContentsHeading = "Custom contents",
            TableOfContentsEmpty = "Custom empty"
        } : SiteText.English;
        var output = Path.Combine(workspace.Root, "out");
        await new SiteGenerator().GenerateWithOptionsAsync(new SiteSettings
        {
            Title = "Docs",
            Language = "en",
            BaseUrl = "https://example.test/"
        }, [], output, true, new() { Text = text },
            new() { Extensions = [docs], BuildTimestamp = DateTimeOffset.UnixEpoch }, default);

        foreach (var variant in new[] { (Locale: "en", Text: text), (Locale: "ja", Text: customizeText ? text : SiteText.Japanese) })
        {
            var headed = await File.ReadAllTextAsync(Path.Combine(output, "guide", variant.Locale, "with-heading", "index.html"));
            var empty = await File.ReadAllTextAsync(Path.Combine(output, "guide", variant.Locale, "without-heading", "index.html"));
            await Assert.That(headed).Contains($"<h2 id=\"post-toc-title\">{variant.Text.TableOfContentsHeading}</h2>");
            await Assert.That(headed).Contains($"<nav class=\"toc-nav\" aria-label=\"{variant.Text.TableOfContentsHeading}\">");
            await Assert.That(headed).Contains("<a data-toc-link href=\"#section\">Section</a>");
            await Assert.That(empty).Contains($"<h2 id=\"post-toc-title\">{variant.Text.TableOfContentsHeading}</h2>");
            await Assert.That(empty).Contains($"<p>{variant.Text.TableOfContentsEmpty}</p>");
        }
    }

    [Test]
    public async Task ExplicitPageLanguageLocalizesBuiltInShellWithoutChangingTheSiteContext()
    {
        var context = PageRenderingContext.Create(new SiteSettings { Title = "Docs", Language = "ja" });
        var layout = new DocsPageLayout();
        string Render(string? locale) => layout.Render(new SitePage<PageLayoutContent>(new("guide"),
            SiteRoute.ForFile("guide.html"), new(Html.UnsafeRaw("<h1>Guide</h1>")),
            new("Guide") { Language = locale }), context).ToHtmlString();
        var japanese = Render("ja-JP");
        await Assert.That(japanese).Contains("本文へ移動");
        await Assert.That(japanese).Contains("aria-label=\"ダークモード\"");
        await Assert.That(japanese).Contains(">メニュー</button>");
        await Assert.That(japanese).Contains("Docsで生成しました。");
        await Assert.That(japanese).Contains("<html lang=\"ja-JP\"");
        var unspecified = Render(null);
        await Assert.That(unspecified).Contains("Skip to main content");
        await Assert.That(unspecified).Contains("aria-label=\"Dark mode\"");
        await Assert.That(unspecified).Contains("Generated by Docs.");
        await Assert.That(ReferenceEquals(context.Text, SiteText.English)).IsTrue();
        await Assert.That(Render("en")).IsEqualTo(unspecified.Replace("lang=\"ja\"", "lang=\"en\"", StringComparison.Ordinal));
    }
}
