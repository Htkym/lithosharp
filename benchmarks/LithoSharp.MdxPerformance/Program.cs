using System.Diagnostics;
using System.Text.Json;
using LithoSharp;
using LithoSharp.Build;
using LithoSharp.Configuration;
using LithoSharp.Documentation;
using LithoSharp.Mdx;

if (args.Length != 3 || !int.TryParse(args[0], out var size) || size is not (100 or 1000 or 10000))
    throw new ArgumentException("Usage: LithoSharp.MdxPerformance <100|1000|10000> <restored-worker-directory> <new-result-directory>");
var worker = Path.GetFullPath(args[1]);
var root = Path.GetFullPath(args[2]);
if (Directory.Exists(root)) throw new ArgumentException("Use a new result directory to measure a cold build.");
var source = Path.Combine(root, "content");
Directory.CreateDirectory(source);
await File.WriteAllTextAsync(Path.Combine(root, "measurements.json"), "{}");
await File.WriteAllTextAsync(Path.Combine(root, "package.json"), "{\"name\":\"mdx-performance-corpus\",\"private\":true}");
await File.WriteAllTextAsync(Path.Combine(root, "package-lock.json"), "{\"name\":\"mdx-performance-corpus\",\"lockfileVersion\":3,\"packages\":{}}");
await File.WriteAllTextAsync(Path.Combine(source, "shared.css"), ".corpus{color:#123456}");
await File.WriteAllTextAsync(Path.Combine(source, "icon.svg"), "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"8\" height=\"8\"><path d=\"M0 0h8v8H0z\" fill=\"red\"/></svg>");
var component = Path.Combine(source, "Counter.jsx");
await File.WriteAllTextAsync(component, "import {useState} from 'react';export default function Counter({initial=3}){const [n,set]=useState(initial);return <button onClick={()=>set(n+1)}>Count {n}</button>}");
for (var index = 0; index < size; index++)
{
    var section = $"section-{index / 100:D3}";
    Directory.CreateDirectory(Path.Combine(source, section));
    var body = "---\ntitle: Document " + index + "\ndisplayed_sidebar: " + section + "\n---\nimport '../shared.css';\nimport icon from '../icon.svg';\n"
        + (index % 10 < 2 ? "import Counter from '../Counter.jsx';\n" : "")
        + "\n# Document " + index + "\n\n## Searchable section\n\n日本語 API Example.GetAsync documentation.\n\n"
        + string.Concat(Enumerable.Repeat("A fixed paragraph explains the API, cancellation and return values.\n\n", 8))
        + "<img src={icon} alt=\"Corpus icon\" className=\"corpus\" />\n"
        + (index % 10 == 0 ? "<Counter />\n" : index % 10 == 1 ? "<Island component={Counter} strategy=\"load\" />\n" : "");
    await File.WriteAllTextAsync(Path.Combine(source, section, $"page-{index:D5}.mdx"), body);
}
DocumentationSite Create(string prefix)
{
    var docs = new DocumentationSite(new(root, worker) { Cacheable = true, Hydration = "selective", Timeout = TimeSpan.FromMinutes(15) });
    docs.AddCollection(new("corpus", [new("current", "en", source, prefix)]) { UseMdx = true,
        Sidebars = Enumerable.Range(0, size / 100).ToDictionary(index => $"section-{index:D3}", index => (IReadOnlyList<SidebarItem>)[new("autogenerated") { Directory = $"section-{index:D3}" }]) });
    return docs;
}
var extension = Create("guide");
var output = Path.Combine(root, "site");
var site = new SiteSettings { Title = "MDX performance corpus", BaseUrl = "https://example.test/product/", Language = "en" };
var customization = new SiteCustomization { Template = new DocsSiteTemplate() };
var measurements = new List<object>();
SiteBuildPlan? previous = null;
async Task Measure(string name, bool clean = false)
{
    GC.Collect(); GC.WaitForPendingFinalizers(); GC.Collect();
    var allocated = GC.GetTotalAllocatedBytes(true);
    var timer = Stopwatch.StartNew();
    var result = await new SiteGenerator().GenerateWithOptionsAsync(site, [], output, clean, customization,
        new() { Extensions = [extension], BuildTimestamp = DateTimeOffset.Parse("2026-01-01T00:00:00Z"), PreviousBuildPlan = previous }, default);
    timer.Stop();
    allocated = GC.GetTotalAllocatedBytes(true) - allocated;
    previous = result.BuildPlan;
    var work = new { name, elapsedMilliseconds = timer.Elapsed.TotalMilliseconds, dotnetAllocatedBytes = allocated,
        mdx = extension.MdxMetrics, cacheHits = result.BuildReport.CacheHitCount, cacheMisses = result.BuildReport.CacheMissCount,
        generatedFiles = result.GeneratedFiles.Count, outputBytes = result.GeneratedFiles.Sum(file => new FileInfo(file).Length) };
    measurements.Add(work);
    Console.WriteLine(JsonSerializer.Serialize(work));
    await File.WriteAllTextAsync(Path.Combine(root, "measurements.json"), JsonSerializer.Serialize(new { schema = 1, size,
        corpus = "80% static, 10% page hydration, 10% load islands; shared CSS, SVG and Counter; eight fixed paragraphs; separate 100-document sidebars",
        runtime = Environment.Version.ToString(), os = System.Runtime.InteropServices.RuntimeInformation.OSDescription,
        nodeMemory = "Heap-used snapshot after each worker response, not a peak", measurements }, new JsonSerializerOptions { WriteIndented = true }));
}
try
{
    await Measure("cold", true);
    await Measure("warm-cache", true);
    await Measure("no-op");
    await File.AppendAllTextAsync(Path.Combine(source, "section-000", "page-00002.mdx"), "\nOne-page change.\n");
    await Measure("one-page");
    await File.WriteAllTextAsync(component, (await File.ReadAllTextAsync(component)).Replace("Count ", "Total ", StringComparison.Ordinal));
    await Measure("shared-component");
    await File.AppendAllTextAsync(Path.Combine(source, "shared.css"), "\n.corpus{border:1px solid blue}");
    await Measure("shared-css");
    await File.WriteAllTextAsync(Path.Combine(source, "icon.svg"), "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"8\" height=\"8\"><circle cx=\"4\" cy=\"4\" r=\"3\" fill=\"blue\"/></svg>");
    await Measure("shared-image");
    customization = customization with { Theme = new SiteThemeOptions { ThemeColor = "#7c3aed" } };
    await Measure("layout");
    await extension.DisposeAsync();
    extension = Create("manual");
    await Measure("route");
    await File.AppendAllTextAsync(Path.Combine(root, "package-lock.json"), "\n");
    await Measure("lockfile");
}
finally { await extension.DisposeAsync(); }
